// PXL Classroom - reading a grade out of a GitHub check run.
//
// ONE implementation, shared by the CLI (`pxl-classroom grade`), the SPA
// (`AssignmentDetailView` via `frontend/src/lib/check-run-score.js`) and any
// script that needs it. There were two byte-identical copies before this
// module existed, which is the fork `lib/effective-deadline.mjs` and
// `frontend/src/lib/countdown.js` exist to prevent.
//
// Dependency-free and isomorphic on purpose: the SPA bundles it, and
// `tests/check-run-score.test.mjs` imports it under plain Node.
//
// WHERE THE SCORE ACTUALLY LIVES. Both copies searched
// `output.title` / `output.summary` / `output.text` for a `Points X/Y` string
// and found nothing, every time. A check run created by GitHub Actions has no
// output body at all - confirmed against a live
// `classroom-resources/autograding-grading-reporter@v1` run on 2026-08-25:
//
//   output.title: null   output.summary: null   annotations_count: 4
//   notice "Autograding report"    {"totalPoints":0,"maxPoints":170}
//   notice "Autograding complete"  Points 0/170
//
// The reporter calls `core.notice()`, so the numbers are **annotations**,
// fetched separately from `GET /repos/{o}/{r}/check-runs/{id}/annotations`.
// With that never read, every parse fell through to the binary conclusion
// fallback: full marks for a green run, zero for anything else, and never a
// partial score. A 15/20 was recorded as 0.

// Rebuilt per call rather than hoisted with /g - a shared literal carrying a
// sticky flag keeps `lastIndex` between calls and matches only sometimes,
// which is the bug `lib/public-text.mjs` documents one module over.
const pointsPattern = () => /Points\s*:?\s*([0-9]+(?:\.[0-9]+)?)\s*\/\s*([0-9]+(?:\.[0-9]+)?)/i;

// The reporter's machine-readable line. Matched loosely and then parsed as
// JSON, so a future field ordering or an added key does not break it.
const reportJsonPattern = () => /\{[^{}]*"totalPoints"\s*:\s*-?[0-9.]+[^{}]*\}/;

/**
 * Choose the check run carrying the autograding result, or NULL.
 *
 * The job name is what surfaces here - `run-autograding-tests` for a workflow
 * generated by GitHub Classroom, `Autograding` for one generated by
 * `provisioning/provision.mjs`. Both contain "grad".
 *
 * NULL RATHER THAN `runs[0]`, and this is a grading-integrity fix rather than
 * tidiness. A student is admin on their own repository. Delete the autograding
 * workflow, add any workflow of their own that goes green, and the fallback
 * handed that run to parseCheckRunScore - which finds no annotations, reports
 * `matched: false`, and awards `fallbackTotal` for `conclusion: "success"`.
 * Full marks, from a check the lecturer never wrote.
 *
 * "There is a green check run here" is not evidence that grading ran. A caller
 * that gets null must say the autograding run is missing, exactly as it already
 * says so for an empty list.
 */
export function pickAutogradeCheckRun(checkRuns) {
  const runs = Array.isArray(checkRuns) ? checkRuns : [];
  return runs.find((r) => /grad|classroom/i.test(r?.name || "")) || null;
}

function scoreFrom(text) {
  if (!text) return null;

  const json = text.match(reportJsonPattern());
  if (json) {
    try {
      const doc = JSON.parse(json[0]);
      const earned = Number(doc.totalPoints);
      const total = Number(doc.maxPoints);
      if (Number.isFinite(earned) && Number.isFinite(total)) {
        return { earned, total, source: "annotation-json" };
      }
    } catch {
      // Not JSON after all - fall through to the human-readable line.
    }
  }

  const points = text.match(pointsPattern());
  if (points) {
    return { earned: parseFloat(points[1]), total: parseFloat(points[2]), source: "points" };
  }

  return null;
}

/**
 * The conclusions under which a check run represents a grading attempt that
 * actually happened. `success` is a pass, `failure` is a real zero - the
 * student's own code broke the run - and EVERYTHING ELSE is neither.
 *
 * `skipped` is why this exists. A job gated by `if:` still produces a check
 * run, measured live 2026-09-04 on PXL-2TIN-CloudEssentials-2627's
 * proef-pe1-d-ries:
 *
 *   9c4e1867 "Initial commit"  run-autograding-tests  conclusion=skipped  annotations=0
 *   44fbe7f0 "einde examen"    run-autograding-tests  conclusion=success  annotations=3
 *
 * That template gates grading on `github.event.head_commit.message ==
 * 'einde examen'`, so every commit that is not the hand-in carries a check run
 * with no annotations - and the fallback below awarded it 0, written into the
 * grade table and the CSV export as if somebody had measured it. It is the same
 * mistake `pickAutogradeCheckRun` refuses one function up: no grading run at
 * this commit is NOT a zero and NOT a pass.
 *
 * `cancelled`, `timed_out`, `stale`, `neutral` and `action_required` are here
 * for the same reason, as is a run with no conclusion at all - one still
 * queued or in progress is not a result yet.
 */
const GRADED_CONCLUSIONS = new Set(["success", "failure"]);

/**
 * Extract `{ earned, total, passed, matched, graded, summaryText, source }`
 * from a check run plus its annotations.
 *
 * `annotations` is REQUIRED and must be an array. It used to be the second
 * positional argument's slot for `defaultTotal`, so a caller that was not
 * updated would silently grade the whole cohort against `[]` - the type check
 * turns that into a loud failure instead.
 */
export function parseCheckRunScore(run, annotations, fallbackTotal = 0) {
  if (!Array.isArray(annotations)) {
    throw new TypeError(
      "parseCheckRunScore(run, annotations, fallbackTotal): annotations must be an array",
    );
  }

  const title = run?.output?.title || "";
  const summary = run?.output?.summary || "";
  const text = run?.output?.text || "";

  // Annotations first: that is where a GitHub Actions reporter puts the score,
  // and an `output` body only exists when something deliberately wrote one.
  const annotationText = annotations
    .map((a) => `${a?.title || ""}\n${a?.message || ""}`)
    .join("\n");

  // The runner's own `warning` annotations are not about the grade. Live, the
  // first one is a Node deprecation notice several lines long, and with no
  // output body to fall back on it became the whole "summary" of a student's
  // result. Kept out of the displayed text, but NOT out of the text the score
  // is parsed from - a reporter is free to use any level it likes.
  const summaryAnnotations = annotations
    .filter((a) => a?.annotation_level !== "warning")
    .map((a) => `${a?.title || ""}\n${a?.message || ""}`)
    .join("\n")
    .trim();

  const found = scoreFrom(annotationText) || scoreFrom(`${title}\n${summary}\n${text}`);

  if (found) {
    return {
      earned: found.earned,
      total: found.total,
      passed: found.earned >= found.total && found.total > 0,
      matched: true,
      graded: true,
      source: found.source,
      summaryText: summary || text || title || summaryAnnotations,
    };
  }

  // Nothing said a number, so the conclusion is all there is - and it only
  // means something when the run actually ran. `graded: false` is not a score a
  // caller may round down and record; it is "this commit has no grade", the
  // same outcome as an empty check-run list.
  const conclusion = run?.conclusion || "";
  if (!GRADED_CONCLUSIONS.has(conclusion)) {
    return {
      earned: 0,
      total: fallbackTotal,
      passed: false,
      matched: false,
      graded: false,
      source: "not-run",
      conclusion: conclusion || null,
      summaryText: summary || text || title || summaryAnnotations,
    };
  }

  // A run that ran and said no number. All this knows is whether it was green,
  // which is an all-or-nothing grade and is reported as such (`matched: false`)
  // so a caller can tell it apart from a real score.
  const passed = conclusion === "success";
  return {
    earned: passed ? fallbackTotal : 0,
    total: fallbackTotal,
    passed,
    matched: false,
    graded: true,
    source: "conclusion",
    summaryText: summary || text || title || summaryAnnotations,
  };
}
